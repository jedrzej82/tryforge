/**
 * Automatic Model Generator
 * Generates database models in multiple formats (Prisma, Sequelize, TypeORM, Mongoose)
 */

const fs = require('fs-extra');
const path = require('path');
const chalk = require('chalk');
const ora = require('ora');
const { beautify } = require('js-beautify');

class ModelGenerator {
  constructor() {
    this.supportedORMs = ['prisma', 'sequelize', 'typeorm', 'mongoose'];
  }

  /**
   * Generate all models for a project
   * @param {Array} models - List of model definitions
   * @param {string} projectPath - Project root path
   * @param {Object} options - Generation options
   */
  async generateModels(models, projectPath, options = {}) {
    const orm = options.orm || 'prisma';
    const language = options.language || 'typescript';

    console.log(chalk.cyan(`\n🏗️  Generating ${models.length} models using ${orm}...\n`));

    const results = [];

    for (const model of models) {
      const spinner = ora(`Generating ${model.name}...`).start();

      try {
        let result;

        switch (orm) {
          case 'prisma':
            result = await this.generatePrismaModel(model, projectPath, options);
            break;
          case 'sequelize':
            result = await this.generateSequelizeModel(model, projectPath, options);
            break;
          case 'typeorm':
            result = await this.generateTypeORMModel(model, projectPath, options);
            break;
          case 'mongoose':
            result = await this.generateMongooseModel(model, projectPath, options);
            break;
          default:
            throw new Error(`Unsupported ORM: ${orm}`);
        }

        spinner.succeed(`Generated ${model.name}`);
        results.push(result);
      } catch (error) {
        spinner.fail(`Failed to generate ${model.name}: ${error.message}`);
        results.push({ success: false, model: model.name, error: error.message });
      }
    }

    // Generate migrations
    if (options.generateMigrations !== false) {
      await this.generateMigrations(models, projectPath, orm);
    }

    // Generate relationships
    if (orm !== 'prisma') { // Prisma handles relationships in schema
      await this.generateRelationships(models, projectPath, orm);
    }

    return results;
  }

  /**
   * Generate Prisma model
   */
  async generatePrismaModel(model, projectPath, options) {
    const schemaPath = path.join(projectPath, 'prisma', 'schema.prisma');

    // Ensure prisma directory exists
    await fs.ensureDir(path.dirname(schemaPath));

    // Read existing schema or create new
    let schema = '';
    if (await fs.pathExists(schemaPath)) {
      schema = await fs.readFile(schemaPath, 'utf8');
    } else {
      // Create basic Prisma schema
      schema = `// Prisma Schema
// Generated by TryForge

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

generator client {
  provider = "prisma-client-js"
}

`;
    }

    // Check if model already exists
    if (schema.includes(`model ${model.name}`)) {
      console.log(chalk.yellow(`  Model ${model.name} already exists in Prisma schema`));
      return { success: true, skipped: true };
    }

    // Generate model definition
    const modelDef = this.generatePrismaModelDefinition(model);

    // Append to schema
    schema += `\n${modelDef}\n`;

    // Write schema
    await fs.writeFile(schemaPath, schema);

    return { success: true, path: schemaPath };
  }

  /**
   * Generate Prisma model definition
   */
  generatePrismaModelDefinition(model) {
    let def = `model ${model.name} {\n`;

    // Add fields
    model.fields.forEach(field => {
      const prismaField = this.convertToPrismaField(field);
      def += `  ${prismaField}\n`;
    });

    // Add relationships
    if (model.relationships) {
      model.relationships.forEach(rel => {
        def += `  ${this.convertToPrismaRelationship(rel, model.name)}\n`;
      });
    }

    // Add indexes
    if (model.indexes && model.indexes.length > 0) {
      def += `\n`;
      model.indexes.forEach(index => {
        def += `  @@index([${index}])\n`;
      });
    }

    def += `}\n`;

    return def;
  }

  /**
   * Convert field to Prisma format
   */
  convertToPrismaField(field) {
    const typeMap = {
      'uuid': 'String',
      'string': 'String',
      'text': 'String',
      'integer': 'Int',
      'decimal': 'Decimal',
      'float': 'Float',
      'boolean': 'Boolean',
      'timestamp': 'DateTime',
      'date': 'DateTime',
      'enum': field.values ? `${field.name.charAt(0).toUpperCase() + field.name.slice(1)}Enum` : 'String'
    };

    let fieldDef = `${field.name}`;

    // Type
    const prismaType = typeMap[field.type] || 'String';
    fieldDef += ` ${prismaType}`;

    // Optional/Required
    if (!field.required && !field.primary) {
      fieldDef += '?';
    }

    // Attributes
    const attrs = [];

    if (field.primary) {
      attrs.push('@id');
      if (field.type === 'uuid') {
        attrs.push('@default(uuid())');
      } else {
        attrs.push('@default(autoincrement())');
      }
    }

    if (field.unique) {
      attrs.push('@unique');
    }

    if (field.default && !field.primary) {
      if (field.default === 'now') {
        attrs.push('@default(now())');
      } else if (typeof field.default === 'string') {
        attrs.push(`@default("${field.default}")`);
      } else {
        attrs.push(`@default(${field.default})`);
      }
    }

    if (field.hidden) {
      attrs.push('@map("_password")'); // Example: map to different column name
    }

    if (attrs.length > 0) {
      fieldDef += ` ${attrs.join(' ')}`;
    }

    return fieldDef;
  }

  /**
   * Convert relationship to Prisma format
   */
  convertToPrismaRelationship(rel, modelName) {
    switch (rel.type) {
      case 'hasMany':
        return `${rel.model.toLowerCase()}s ${rel.model}[]`;
      case 'belongsTo':
      case 'manyToOne':
        return `${rel.model.toLowerCase()} ${rel.model}? @relation(fields: [${rel.foreignKey}], references: [id])`;
      case 'hasOne':
        return `${rel.model.toLowerCase()} ${rel.model}?`;
      case 'manyToMany':
        return `${rel.model.toLowerCase()}s ${rel.model}[]`;
      default:
        return `${rel.model.toLowerCase()} ${rel.model}?`;
    }
  }

  /**
   * Generate Sequelize model
   */
  async generateSequelizeModel(model, projectPath, options) {
    const modelsDir = path.join(projectPath, 'backend', 'src', 'models');
    await fs.ensureDir(modelsDir);

    const modelPath = path.join(modelsDir, `${model.name}.js`);

    // Check if model exists
    if (await fs.pathExists(modelPath)) {
      console.log(chalk.yellow(`  Model ${model.name} already exists`));
      return { success: true, skipped: true };
    }

    const code = this.generateSequelizeCode(model);
    await fs.writeFile(modelPath, code);

    return { success: true, path: modelPath };
  }

  /**
   * Generate Sequelize model code
   */
  generateSequelizeCode(model) {
    const code = `const { Model, DataTypes } = require('sequelize');

class ${model.name} extends Model {
  static init(sequelize) {
    return super.init({
${model.fields.map(f => this.convertToSequelizeField(f)).join(',\n')}
    }, {
      sequelize,
      modelName: '${model.name}',
      tableName: '${model.name.toLowerCase()}s',
      timestamps: true,
      underscored: true,
    });
  }

  static associate(models) {
${model.relationships ? model.relationships.map(r => this.convertToSequelizeRelationship(r, model.name)).join('\n') : '    // No relationships'}
  }
}

module.exports = ${model.name};
`;

    return beautify(code, { indent_size: 2 });
  }

  /**
   * Convert field to Sequelize format
   */
  convertToSequelizeField(field) {
    const typeMap = {
      'uuid': 'DataTypes.UUID',
      'string': 'DataTypes.STRING',
      'text': 'DataTypes.TEXT',
      'integer': 'DataTypes.INTEGER',
      'decimal': 'DataTypes.DECIMAL(10, 2)',
      'float': 'DataTypes.FLOAT',
      'boolean': 'DataTypes.BOOLEAN',
      'timestamp': 'DataTypes.DATE',
      'date': 'DataTypes.DATEONLY',
      'enum': `DataTypes.ENUM(${field.values ? field.values.map(v => `'${v}'`).join(', ') : "'value'"})`
    };

    const attrs = [];

    const type = typeMap[field.type] || 'DataTypes.STRING';
    attrs.push(`type: ${type}`);

    if (field.primary) {
      attrs.push('primaryKey: true');
      if (field.type === 'uuid') {
        attrs.push('defaultValue: DataTypes.UUIDV4');
      } else {
        attrs.push('autoIncrement: true');
      }
    }

    if (field.required) {
      attrs.push('allowNull: false');
    }

    if (field.unique) {
      attrs.push('unique: true');
    }

    if (field.default && !field.primary) {
      if (field.default === 'now') {
        attrs.push('defaultValue: DataTypes.NOW');
      } else {
        attrs.push(`defaultValue: ${JSON.stringify(field.default)}`);
      }
    }

    return `      ${field.name}: {\n        ${attrs.join(',\n        ')}\n      }`;
  }

  /**
   * Convert relationship to Sequelize format
   */
  convertToSequelizeRelationship(rel, modelName) {
    switch (rel.type) {
      case 'hasMany':
        return `    this.hasMany(models.${rel.model}, { foreignKey: '${rel.foreignKey}', as: '${rel.model.toLowerCase()}s' });`;
      case 'belongsTo':
        return `    this.belongsTo(models.${rel.model}, { foreignKey: '${rel.foreignKey}', as: '${rel.model.toLowerCase()}' });`;
      case 'hasOne':
        return `    this.hasOne(models.${rel.model}, { foreignKey: '${rel.foreignKey}', as: '${rel.model.toLowerCase()}' });`;
      case 'manyToMany':
        return `    this.belongsToMany(models.${rel.model}, { through: '${modelName}${rel.model}', as: '${rel.model.toLowerCase()}s' });`;
      default:
        return `    // ${rel.type} relationship to ${rel.model}`;
    }
  }

  /**
   * Generate TypeORM model
   */
  async generateTypeORMModel(model, projectPath, options) {
    const modelsDir = path.join(projectPath, 'backend', 'src', 'entities');
    await fs.ensureDir(modelsDir);

    const modelPath = path.join(modelsDir, `${model.name}.ts`);

    if (await fs.pathExists(modelPath)) {
      console.log(chalk.yellow(`  Model ${model.name} already exists`));
      return { success: true, skipped: true };
    }

    const code = this.generateTypeORMCode(model);
    await fs.writeFile(modelPath, code);

    return { success: true, path: modelPath };
  }

  /**
   * Generate TypeORM model code
   */
  generateTypeORMCode(model) {
    const code = `import { Entity, PrimaryGeneratedColumn, Column, CreateDateColumn, UpdateDateColumn } from 'typeorm';

@Entity('${model.name.toLowerCase()}s')
export class ${model.name} {
${model.fields.map(f => this.convertToTypeORMField(f)).join('\n\n')}

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;
}
`;

    return code;
  }

  /**
   * Convert field to TypeORM format
   */
  convertToTypeORMField(field) {
    const typeMap = {
      'uuid': 'uuid',
      'string': 'varchar',
      'text': 'text',
      'integer': 'int',
      'decimal': 'decimal',
      'float': 'float',
      'boolean': 'boolean',
      'timestamp': 'timestamp',
      'date': 'date',
      'enum': 'enum'
    };

    const decorators = [];

    if (field.primary) {
      decorators.push('@PrimaryGeneratedColumn("uuid")');
    } else {
      const options = [];

      if (field.unique) {
        options.push('unique: true');
      }

      if (!field.required) {
        options.push('nullable: true');
      }

      if (field.default && field.default !== 'now') {
        options.push(`default: ${JSON.stringify(field.default)}`);
      }

      const type = typeMap[field.type] || 'varchar';
      const optionsStr = options.length > 0 ? `, { ${options.join(', ')} }` : '';

      if (field.type === 'enum' && field.values) {
        decorators.push(`@Column({ type: 'enum', enum: [${field.values.map(v => `'${v}'`).join(', ')}]${optionsStr} })`);
      } else {
        decorators.push(`@Column('${type}'${optionsStr})`);
      }
    }

    const tsType = this.getTypeScriptType(field);

    return `  ${decorators.join('\n  ')}\n  ${field.name}: ${tsType};`;
  }

  /**
   * Get TypeScript type for field
   */
  getTypeScriptType(field) {
    const typeMap = {
      'uuid': 'string',
      'string': 'string',
      'text': 'string',
      'integer': 'number',
      'decimal': 'number',
      'float': 'number',
      'boolean': 'boolean',
      'timestamp': 'Date',
      'date': 'Date',
      'enum': field.values ? field.values.map(v => `'${v}'`).join(' | ') : 'string'
    };

    return typeMap[field.type] || 'string';
  }

  /**
   * Generate migrations
   */
  async generateMigrations(models, projectPath, orm) {
    console.log(chalk.cyan('\n📝 Generating migrations...\n'));

    const migrationsDir = path.join(projectPath, 'backend', 'migrations');
    await fs.ensureDir(migrationsDir);

    const timestamp = Date.now();

    for (const model of models) {
      const migrationPath = path.join(migrationsDir, `${timestamp}_create_${model.name.toLowerCase()}.js`);
      const migration = this.generateMigrationCode(model, orm);
      await fs.writeFile(migrationPath, migration);
      console.log(chalk.green(`  ✓ Migration for ${model.name}`));
    }
  }

  /**
   * Generate migration code
   */
  generateMigrationCode(model, orm) {
    // Generic SQL migration
    const tableName = `${model.name.toLowerCase()}s`;

    const code = `/**
 * Migration: Create ${model.name} table
 * Generated by TryForge
 */

module.exports = {
  async up(queryInterface, Sequelize) {
    await queryInterface.createTable('${tableName}', {
${model.fields.map(f => this.convertToMigrationField(f)).join(',\n')}
    });

${model.indexes && model.indexes.length > 0 ? this.generateIndexMigrations(tableName, model.indexes) : '    // No indexes'}
  },

  async down(queryInterface, Sequelize) {
    await queryInterface.dropTable('${tableName}');
  }
};
`;

    return beautify(code, { indent_size: 2 });
  }

  /**
   * Convert field to migration format
   */
  convertToMigrationField(field) {
    const typeMap = {
      'uuid': 'Sequelize.UUID',
      'string': 'Sequelize.STRING',
      'text': 'Sequelize.TEXT',
      'integer': 'Sequelize.INTEGER',
      'decimal': 'Sequelize.DECIMAL(10, 2)',
      'float': 'Sequelize.FLOAT',
      'boolean': 'Sequelize.BOOLEAN',
      'timestamp': 'Sequelize.DATE',
      'date': 'Sequelize.DATEONLY'
    };

    const attrs = [];

    const type = typeMap[field.type] || 'Sequelize.STRING';
    attrs.push(`type: ${type}`);

    if (field.primary) {
      attrs.push('primaryKey: true');
      if (field.type === 'uuid') {
        attrs.push('defaultValue: Sequelize.UUIDV4');
      } else {
        attrs.push('autoIncrement: true');
      }
    }

    if (field.required) {
      attrs.push('allowNull: false');
    }

    if (field.unique) {
      attrs.push('unique: true');
    }

    return `      ${field.name}: {\n        ${attrs.join(',\n        ')}\n      }`;
  }

  /**
   * Generate index migrations
   */
  generateIndexMigrations(tableName, indexes) {
    return indexes.map(index =>
      `    await queryInterface.addIndex('${tableName}', ['${index}']);`
    ).join('\n');
  }

  /**
   * Generate relationships
   */
  async generateRelationships(models, projectPath, orm) {
    console.log(chalk.cyan('\n🔗 Generating relationships...\n'));
    // Relationships are handled in model definitions for Sequelize/TypeORM
    console.log(chalk.green('  ✓ Relationships defined in models'));
  }

  /**
   * Generate Mongoose model
   */
  async generateMongooseModel(model, projectPath, options) {
    const modelsDir = path.join(projectPath, 'backend', 'src', 'models');
    await fs.ensureDir(modelsDir);

    const modelPath = path.join(modelsDir, `${model.name}.js`);

    if (await fs.pathExists(modelPath)) {
      console.log(chalk.yellow(`  Model ${model.name} already exists`));
      return { success: true, skipped: true };
    }

    const code = this.generateMongooseCode(model);
    await fs.writeFile(modelPath, code);

    return { success: true, path: modelPath };
  }

  /**
   * Generate Mongoose model code
   */
  generateMongooseCode(model) {
    const code = `const mongoose = require('mongoose');

const ${model.name}Schema = new mongoose.Schema({
${model.fields.filter(f => !f.primary).map(f => this.convertToMongooseField(f)).join(',\n')}
}, {
  timestamps: true
});

${model.indexes && model.indexes.length > 0 ? this.generateMongooseIndexes(model.indexes) : ''}

module.exports = mongoose.model('${model.name}', ${model.name}Schema);
`;

    return beautify(code, { indent_size: 2 });
  }

  /**
   * Convert field to Mongoose format
   */
  convertToMongooseField(field) {
    const typeMap = {
      'uuid': 'String',
      'string': 'String',
      'text': 'String',
      'integer': 'Number',
      'decimal': 'Number',
      'float': 'Number',
      'boolean': 'Boolean',
      'timestamp': 'Date',
      'date': 'Date'
    };

    const attrs = [];
    const type = typeMap[field.type] || 'String';
    attrs.push(`type: ${type}`);

    if (field.required) {
      attrs.push('required: true');
    }

    if (field.unique) {
      attrs.push('unique: true');
    }

    if (field.default && field.default !== 'now') {
      attrs.push(`default: ${JSON.stringify(field.default)}`);
    }

    if (field.type === 'enum' && field.values) {
      attrs.push(`enum: [${field.values.map(v => `'${v}'`).join(', ')}]`);
    }

    return `  ${field.name}: {\n    ${attrs.join(',\n    ')}\n  }`;
  }

  /**
   * Generate Mongoose indexes
   */
  generateMongooseIndexes(indexes) {
    return indexes.map(index =>
      `${model.name}Schema.index({ ${index}: 1 });`
    ).join('\n');
  }
}

module.exports = ModelGenerator;
